import Foundation

// CONTRACT: `Package` in docs/API.md and services/api/src/types/api.ts, plus
// `etaDateOnly`. Decode and encode with WireJSON's coders.

public struct PackageItem: Hashable, Sendable, Codable {
    public var name: String
    /// Amazon CDN URL. Not shown in v1 (DESIGN.md §6, Items).
    public var imageUrl: String?
    public var quantity: Int

    public init(name: String, imageUrl: String? = nil, quantity: Int = 1) {
        self.name = name
        self.imageUrl = imageUrl
        self.quantity = quantity
    }

    public func encode(to encoder: any Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(name, forKey: .name)
        try c.encode(imageUrl, forKey: .imageUrl)
        try c.encode(quantity, forKey: .quantity)
    }
}

public struct Package: Identifiable, Hashable, Sendable, Codable {
    /// Lowercase UUID, generated by the client on create.
    public var id: String
    public var carrier: Carrier
    public var trackingNumber: String
    public var title: String?
    public var merchant: String?
    public var orderId: String?
    public var source: Source
    public var status: Status
    public var statusDetail: String?
    public var eta: ETA
    public var deliveredAt: Date?
    public var lastCheckedAt: Date?
    public var archivedAt: Date?
    public var updatedAt: Date
    public var items: [PackageItem]

    public init(
        id: String, carrier: Carrier, trackingNumber: String, title: String? = nil, merchant: String? = nil,
        orderId: String? = nil, source: Source = .manual, status: Status = .unknown, statusDetail: String? = nil,
        eta: ETA = .none, deliveredAt: Date? = nil, lastCheckedAt: Date? = nil, archivedAt: Date? = nil,
        updatedAt: Date, items: [PackageItem] = []
    ) {
        self.id = id
        self.carrier = carrier
        self.trackingNumber = trackingNumber
        self.title = title
        self.merchant = merchant
        self.orderId = orderId
        self.source = source
        self.status = status
        self.statusDetail = statusDetail
        self.eta = eta
        self.deliveredAt = deliveredAt
        self.lastCheckedAt = lastCheckedAt
        self.archivedAt = archivedAt
        self.updatedAt = updatedAt
        self.items = items
    }

    public var isArchived: Bool { archivedAt != nil }

    /// Row title: title, else merchant, else "UPS ···4784" (DESIGN.md §6).
    public var displayTitle: String {
        if let title, !title.isEmpty { return title }
        if let merchant, !merchant.isEmpty { return merchant }
        return "\(carrier.displayName) ···\(trackingNumber.suffix(4))"
    }

    enum CodingKeys: String, CodingKey {
        case id, carrier, trackingNumber, title, merchant, orderId, source, status, statusDetail
        case etaStart, etaEnd, etaDateOnly
        case deliveredAt, lastCheckedAt, archivedAt, updatedAt, items
    }

    public init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        carrier = try c.decode(Carrier.self, forKey: .carrier)
        trackingNumber = try c.decode(String.self, forKey: .trackingNumber)
        title = try c.decodeIfPresent(String.self, forKey: .title)
        merchant = try c.decodeIfPresent(String.self, forKey: .merchant)
        orderId = try c.decodeIfPresent(String.self, forKey: .orderId)
        source = try c.decode(Source.self, forKey: .source)
        status = try c.decode(Status.self, forKey: .status)
        statusDetail = try c.decodeIfPresent(String.self, forKey: .statusDetail)
        eta = try ETA.decode(from: c, start: .etaStart, end: .etaEnd, dateOnly: .etaDateOnly)
        deliveredAt = try c.decodeIfPresent(Date.self, forKey: .deliveredAt)
        lastCheckedAt = try c.decodeIfPresent(Date.self, forKey: .lastCheckedAt)
        archivedAt = try c.decodeIfPresent(Date.self, forKey: .archivedAt)
        updatedAt = try c.decode(Date.self, forKey: .updatedAt)
        items = try c.decodeIfPresent([PackageItem].self, forKey: .items) ?? []
    }

    public func encode(to encoder: any Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(id, forKey: .id)
        try c.encode(carrier, forKey: .carrier)
        try c.encode(trackingNumber, forKey: .trackingNumber)
        try c.encode(title, forKey: .title)
        try c.encode(merchant, forKey: .merchant)
        try c.encode(orderId, forKey: .orderId)
        try c.encode(source, forKey: .source)
        try c.encode(status, forKey: .status)
        try c.encode(statusDetail, forKey: .statusDetail)
        try eta.encode(to: &c, start: .etaStart, end: .etaEnd, dateOnly: .etaDateOnly)
        try c.encode(deliveredAt, forKey: .deliveredAt)
        try c.encode(lastCheckedAt, forKey: .lastCheckedAt)
        try c.encode(archivedAt, forKey: .archivedAt)
        try c.encode(updatedAt, forKey: .updatedAt)
        try c.encode(items, forKey: .items)
    }
}
